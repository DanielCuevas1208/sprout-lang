// Package build turns a Sprout project into a single self-contained file.
//
// A bundle inlines every module at its import site. Each import compiles to
// a call to a loader function that caches the module by its file path, so a
// module body still runs exactly once. Member access on the bundled modules
// keeps working because the loader returns module values.
//
// The bundled file runs on the interpreter and the bytecode VM without any
// external files.
package build

import (
	"fmt"
	"sort"
	"strconv"
	"strings"

	"github.com/sprout-lang/sprout/internal/ast"
	"github.com/sprout-lang/sprout/internal/module"
)

const (
	loadedVar = "__sprout_loaded"
	loadFn    = "__sprout_load"
)

// bundleHeader names the helper that caches loaded modules.
const bundleHeader = `// Generated by sprout build.
// This file is a single-file bundle of a Sprout project.

let %s = {}
let %s = fn(name, init) {
    if has(%s, name) {
        return get(%s, name)
    }
    let result = init()
    set(%s, name, result)
    return result
}

`

// Bundle renders the entry program and all its modules as one file.
func Bundle(g *module.Graph) (string, error) {
	if err := checkReservedNames(g); err != nil {
		return "", err
	}
	var b strings.Builder
	fmt.Fprintf(&b, bundleHeader, loadedVar, loadFn, loadedVar, loadedVar, loadedVar)
	em := &bundler{g: g, b: &b}
	em.emitFile(g.Entry, "")
	return b.String(), nil
}

// bundler writes a program with imports inlined as loader calls.
type bundler struct {
	g *module.Graph
	b *strings.Builder
}

// emitFile renders the statements of a file, replacing imports.
//
// Module bodies render with SourceBody so export modifiers disappear. A
// bundled program is a single plain file; it cannot declare exports.
func (e *bundler) emitFile(f *module.File, indent string) {
	for _, s := range f.Prog.Stmts {
		imp, ok := s.(*ast.ImportStmt)
		if !ok {
			e.line(indent, ast.SourceBody(s))
			continue
		}
		e.emitImport(f, imp, indent)
	}
}

// emitImport renders one import as a loader call with an inline module.
func (e *bundler) emitImport(from *module.File, imp *ast.ImportStmt, indent string) {
	target, ok := e.g.Resolve(imp.Path, from.Path)
	if !ok {
		e.line(indent, "let "+imp.Name.Name+" = nil")
		return
	}
	key := e.g.Key(target)
	e.line(indent, "let "+imp.Name.Name+" = "+loadFn+"("+strconv.Quote(key)+", fn() {")
	inner := indent + "    "
	e.emitFile(target, inner)
	if len(target.ExportNames) > 0 {
		e.line(inner, "return "+moduleCall(target, exportMap(target)))
	} else {
		e.line(inner, "return "+moduleCall(target, emptyMap))
	}
	e.line(indent, "})")
}

// exportMap builds a map literal of a module's exported names.
func exportMap(f *module.File) *ast.MapLit {
	entries := make([]ast.MapEntry, 0, len(f.ExportNames))
	for _, name := range f.ExportNames {
		entries = append(entries, ast.MapEntry{
			Key:   &ast.StrLit{Value: name},
			Value: &ast.Ident{Name: name},
		})
	}
	return &ast.MapLit{Entries: entries}
}

// emptyMap is the exports map of a module with no exports.
var emptyMap = &ast.MapLit{}

// moduleCall renders "module(name, exports)" for a target file.
func moduleCall(f *module.File, exports *ast.MapLit) string {
	name := strconv.Quote(module.BaseName(f.Path))
	return "module(" + name + ", " + ast.Source(exports) + ")"
}

// line writes one source statement, indenting every line.
//
// The AST printer renders statements from column zero. Re-indenting each line
// keeps nested module bodies aligned inside their loader closures.
func (e *bundler) line(indent, text string) {
	lines := strings.Split(strings.TrimSuffix(text, "\n"), "\n")
	for _, ln := range lines {
		e.b.WriteString(indent)
		e.b.WriteString(ln)
		e.b.WriteString("\n")
	}
}

// checkReservedNames rejects programs that declare the bundle helpers.
func checkReservedNames(g *module.Graph) error {
	reserved := map[string]bool{loadedVar: true, loadFn: true}
	var names []string
	for _, f := range g.Files() {
		for _, s := range f.Prog.Stmts {
			var name string
			switch n := s.(type) {
			case *ast.LetStmt:
				name = n.Name.Name
			case *ast.FnStmt:
				if n.Receiver == nil {
					name = n.Name.Name
				}
			case *ast.StructStmt:
				name = n.Name.Name
			case *ast.ImportStmt:
				name = n.Name.Name
			}
			if name != "" && reserved[name] {
				names = append(names, name)
			}
		}
	}
	if len(names) > 0 {
		sort.Strings(names)
		return fmt.Errorf("cannot build: %s uses a reserved bundle helper name", strings.Join(names, ", "))
	}
	return nil
}
